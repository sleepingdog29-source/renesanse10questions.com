export const TOTAL = QUESTIONS.length;

export const PUBLIC_QUESTIONS: PublicQuestion[] = QUESTIONS.map((q) => ({
  text: q.text,
  options: q.options,
}));

export function evaluate(answers: (number | null)[]): { score: number; details: AnswerDetail[] } {
  const details = QUESTIONS.map((q, i) => ({
    selected: answers[i] ?? null,
    correct: q.correct,
    explanation: q.explanation,
  }));
  const score = details.filter((d) => d.selected === d.correct).length;
  return { score, details };
}
